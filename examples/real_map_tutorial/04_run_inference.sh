#!/bin/bash
# Step 4: Run inference on 9UGC_A with cryo-EM map reward.
# Energy relaxation runs automatically on the final diffusion step.
# Outputs: <DUMP_DIR>/<config_name>/seed_<N>/
#   predictions/*.cif   final structure (energy-relaxed)
#   reward_history.json per-step reward values
#   profile.json        timing + peak GPU memory
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_ROOT"

export LAYERNORM_TYPE=torch_layernorm
# Checkpoint is auto-downloaded here on first run if not already present.
# Override by setting CHECKPOINT_DIR in your environment before calling this script.
CHECKPOINT_DIR="${CHECKPOINT_DIR:-$HOME/.cache/protenix/checkpoint}"

# ── Configuration ─────────────────────────────────────────────────
# Model checkpoint to use. v0.5.0 and v1.0.0 auto-download on first run.
# protenix-v2 cannot be auto-downloaded outside China (see issue #296).
#   protenix_base_default_v0.5.0   Protenix v0.5.0
#   protenix_base_default_v1.0.0   Protenix v1.0.0
#   protenix-v2                    Protenix v2 (no auto-download outside China, https://github.com/bytedance/Protenix/issues/296)
MODEL_NAME="protenix_base_default_v0.5.0"

# Path to input JSON config (generated by 03_make_cfg.py)
INPUT_JSON="$SCRIPT_DIR/inference_configs/9UGC_A_embedopt_lr0.1.json"

# Output directory for results
DUMP_DIR="$SCRIPT_DIR/output"

# Number of diffusion denoising steps
N_STEPS=100

# Comma-separated random seeds — one output structure per seed
SEEDS="101,42"
# ──────────────────────────────────────────────────────────────────

pixi run python -m embedopt.inference.inference \
    --input_json_path "$INPUT_JSON" \
    --dump_dir "$DUMP_DIR" \
    --model_name "$MODEL_NAME" \
    --load_checkpoint_dir "$CHECKPOINT_DIR" \
    --use_template false \
    --enable_diffusion_shared_vars_cache false \
    --sample_diffusion.N_step "$N_STEPS" \
    --seeds "$SEEDS"
